// 政府行政機關辦公日曆表：落在「平日」的放假日（含補假）。
// 週六、週日由程式另外計算，不需列在這裡。
// 來源：行政院人事行政總處 115 年、116 年政府行政機關辦公日曆表。
// 規則：紀念日、節日逢週六，前一個上班日補假；逢週日，下一個上班日補假。
// 每年新日曆公告後，請依官方日曆表補上。
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Holidays = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  const LIST = {
    // 115 年（2026）：平日放假 16 天，全年放假 120 天
    '2026-01-01': '開國紀念日',
    '2026-02-16': '除夕', '2026-02-17': '春節', '2026-02-18': '春節', '2026-02-19': '春節',
    '2026-02-20': '補假（小年夜逢週日）',
    '2026-02-27': '補假（和平紀念日逢週六）',
    '2026-04-03': '補假（兒童節逢週六）',
    '2026-04-06': '補假（清明節逢週日）',
    '2026-05-01': '勞動節',
    '2026-06-19': '端午節',
    '2026-09-25': '中秋節',
    '2026-09-28': '教師節',
    '2026-10-09': '補假（國慶日逢週六）',
    '2026-10-26': '補假（光復節逢週日）',
    '2026-12-25': '行憲紀念日',
    // 116 年（2027）：平日放假 17 天，全年放假 121 天
    '2027-01-01': '開國紀念日',
    '2027-02-04': '小年夜', '2027-02-05': '除夕', '2027-02-08': '春節',
    '2027-02-09': '補假（春節初一逢週六）', '2027-02-10': '補假（春節初二逢週日）',
    '2027-03-01': '補假（和平紀念日逢週日）',
    '2027-04-05': '清明節',
    '2027-04-06': '補假（兒童節逢週日）',
    '2027-04-30': '補假（勞動節逢週六）',
    '2027-06-09': '端午節',
    '2027-09-15': '中秋節',
    '2027-09-28': '教師節',
    '2027-10-11': '補假（國慶日逢週日）',
    '2027-10-25': '光復節',
    '2027-12-24': '補假（行憲紀念日逢週六）',
    '2027-12-31': '補假（118 年開國紀念日逢週六）',
  };
  const pad = (n) => String(n).padStart(2, '0');
  // 回傳該月落在平日的放假日（日期數字陣列）
  function forMonth(year, month) {
    const prefix = `${year}-${pad(month)}-`;
    return Object.keys(LIST).filter((k) => k.startsWith(prefix)).map((k) => Number(k.slice(8))).sort((a, b) => a - b);
  }
  const covers = (year) => Object.keys(LIST).some((k) => k.startsWith(year + '-'));
  return { LIST, forMonth, covers };
});
